@pytest.mark.parametrize(("a", "b", "want"), DPKG)
def test_dpkg(a, b, want):
    assert dpkg_compare(a, b) == want
    assert dpkg_compare(b, a) == -want


@pytest.mark.parametrize(("a", "b", "want"), RPM)
def test_rpmvercmp(a, b, want):
    assert rpmvercmp(a, b) == want


def test_rpm_evr():
    assert rpm_compare("1:1.0-1.el9", "2.0-1.el9") == 1  # epoch wins
    assert rpm_compare("0:1.0-1.el9", "1.0-1.el9") == 0
    assert rpm_compare("3.0.7-24.el9", "3.0.7-25.el9_2.1") == -1
    assert rpm_compare("1.0-1.module+el8.4.0+557+48ba8b2f", "1.0-1.module+el8.5.0+1+aaaa") == -1
    assert rpm_compare("1.2.3", "1.2.3-9") == 0  # no release on one side: rpm ignores the release


